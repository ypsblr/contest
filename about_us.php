					<p style="text-align:justify;">
						Youth Photographic Society (YPS) was borne In Sep 1971 under the patronage of the then Department of Youth Services & Sports, 
						Government of Karnataka. Among a few hobby groups formed in the State Youth Center, a handful of interested photographers 
						started YPS activities with the guidance of the then Director Mr. Joginder Singh and Mr. Vijay.
						<br /><br />
						Over the years, YPS has grown to be one of the most prestigious and active photographic clubs in the entire country. Today, 
						YPS is one of the oldest and highly acclaimed clubs in India. YPS is fortunate to be associated with many veterans in art 
						photography. The stalwarts in art photography, viz., Late Dr. G. Thomas, Late Mr. C. Rajagopal and Late Mr. E. Hanumantha Rao, 
						have closely guided the growth of YPS along with highly applauded photo-artists like Mr. T.N.A. Perumal, FRPS, MFIAP, Hon.YPS, 
						Mr. B. Srinivasa, FRPS, MFIAP, Hon.YPS and Mr. M.S.Hebbar, AFIAP, Hon.YPS.
						<br/><br/>
						YPS is proud to have the highest number of internationally renowned photographers as its members and the club has been active 
						by their sustained efforts. At the moment, YPS has about 40 members who have been honoured with various international 
						distinctions by various international bodies. The society has, in its folds, both professional and amateur photographers 
						who meet regularly to hone up their skills and senior members have groomed many a amateur photographer to become accomplished 
						photo artists.
						<br/><br/>
						YPS has the distinction of having organized 33 National and 9 International salons. The National salons are held annually, 
						whereas the International salons are held biennially. YPS is a member of FIP and has successfully conducted two FIP 
						Conventions in 1985 and 1995 to the utmost satisfaction of the delegates. These salons and conventions are among the best 
						in the country and the overwhelming response they receive, year after year, is a proof of their popularity.
						<br/><br/>
						YPS celebrated the SILVER JUBILEE in 1996 marking an important milestone in the history of YPS. The WORLD PHOTOGRAPHY DAY 
						on Aug 19 is being celebrated every year  in the society in a distinct manner since 1999.
